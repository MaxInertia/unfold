package tracer

// runtimeSource is the package the instrumented code calls into. It is
// compiled as part of the traced module (added through the overlay at a
// path under the module root), so it may import nothing but the standard
// library and must stay small: it runs once per statement.
//
// Events are written as one short text line each to the file named by
// UNFOLD_TRACE, buffered, and flushed whenever a goroutine's stack drains
// — for a test, that is when the test function returns — so a process that
// exits without warning still leaves everything up to the last completed
// top-level call on disk. UNFOLD_TRACE_MAX caps the event count; past it
// nothing more is recorded and a final "T" line says so.
//
// The goroutine id is parsed from runtime.Stack once per Enter and handed
// back as the handle the function's Line and Exit calls pass in, so the
// per-statement cost is a lock and a buffered write.
const runtimeSource = `// Code generated by unfold trace. DO NOT EDIT.
package unfoldtrace

import (
	"bufio"
	"os"
	"runtime"
	"strconv"
	"sync"
	"time"
)

var (
	mu    sync.Mutex
	out   *bufio.Writer
	start time.Time
	count int
	limit = 200000
	depth = map[int64]int{}
	buf   []byte
)

func init() {
	path := os.Getenv("UNFOLD_TRACE")
	if path == "" {
		return
	}
	f, err := os.Create(path)
	if err != nil {
		return
	}
	if n, err := strconv.Atoi(os.Getenv("UNFOLD_TRACE_MAX")); err == nil && n > 0 {
		limit = n
	}
	out = bufio.NewWriterSize(f, 1<<16)
	start = time.Now()
}

// gid reads "goroutine N [" off the top of this goroutine's stack dump.
func gid() int64 {
	var b [64]byte
	n := runtime.Stack(b[:], false)
	var g int64
	for i := len("goroutine "); i < n; i++ {
		c := b[i]
		if c < '0' || c > '9' {
			break
		}
		g = g*10 + int64(c-'0')
	}
	return g
}

// Enter records that fn (declared on line) began on the calling goroutine
// and returns the handle its Line and Exit calls use. Zero when tracing is
// off, which makes every later call a nil check.
func Enter(fn string, line int) int64 {
	if out == nil {
		return 0
	}
	g := gid()
	mu.Lock()
	depth[g]++
	emit('E', g, line, fn)
	mu.Unlock()
	return g
}

// Line records that the statement on line began.
func Line(g int64, line int) {
	if g == 0 {
		return
	}
	mu.Lock()
	emit('L', g, line, "")
	mu.Unlock()
}

// Exit records that the function on top of g's stack returned.
func Exit(g int64) {
	if g == 0 {
		return
	}
	mu.Lock()
	emit('X', g, 0, "")
	depth[g]--
	if depth[g] <= 0 {
		delete(depth, g)
		out.Flush()
	}
	mu.Unlock()
}

func emit(kind byte, g int64, line int, fn string) {
	if count >= limit {
		if count == limit {
			count++
			out.WriteString("T\n")
			out.Flush()
		}
		return
	}
	count++
	buf = append(buf[:0], kind, ' ')
	buf = strconv.AppendInt(buf, g, 10)
	buf = append(buf, ' ')
	buf = strconv.AppendInt(buf, int64(time.Since(start)), 10)
	if kind != 'X' {
		buf = append(buf, ' ')
		buf = strconv.AppendInt(buf, int64(line), 10)
	}
	if kind == 'E' {
		buf = append(buf, ' ')
		buf = append(buf, fn...)
	}
	buf = append(buf, '\n')
	out.Write(buf)
}
`
